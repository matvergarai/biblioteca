-- Esquema del foro en linea para Oracle.
-- Hibernate tambien puede crear estas tablas con spring.jpa.hibernate.ddl-auto=update.

CREATE SEQUENCE USUARIO_SEQ START WITH 1 INCREMENT BY 1;
CREATE SEQUENCE CATEGORIA_SEQ START WITH 1 INCREMENT BY 1;
CREATE SEQUENCE TEMA_SEQ START WITH 1 INCREMENT BY 1;
CREATE SEQUENCE COMENTARIO_SEQ START WITH 1 INCREMENT BY 1;

CREATE TABLE USUARIOS (
	ID NUMBER(19) PRIMARY KEY,
	NOMBRE VARCHAR2(120 CHAR) NOT NULL,
	CORREO VARCHAR2(150 CHAR) NOT NULL,
	CLAVE VARCHAR2(100 CHAR) NOT NULL,
	ROL VARCHAR2(20 CHAR) NOT NULL,
	CONSTRAINT UK_USUARIOS_CORREO UNIQUE (CORREO),
	CONSTRAINT CK_USUARIOS_ROL CHECK (ROL IN ('USUARIO', 'ADMINISTRADOR'))
);

CREATE TABLE CATEGORIAS (
	ID NUMBER(19) PRIMARY KEY,
	NOMBRE VARCHAR2(80 CHAR) NOT NULL,
	DESCRIPCION VARCHAR2(250 CHAR) NOT NULL,
	CONSTRAINT UK_CATEGORIAS_NOMBRE UNIQUE (NOMBRE)
);

CREATE TABLE TEMAS (
	ID NUMBER(19) PRIMARY KEY,
	TITULO VARCHAR2(200 CHAR) NOT NULL,
	CONTENIDO VARCHAR2(4000 CHAR) NOT NULL,
	FECHA_CREACION TIMESTAMP NOT NULL,
	ESTADO VARCHAR2(20 CHAR) NOT NULL,
	CATEGORIA_ID NUMBER(19) NOT NULL,
	AUTOR_ID NUMBER(19) NOT NULL,
	CONSTRAINT CK_TEMAS_ESTADO CHECK (ESTADO IN ('PUBLICADO', 'BANEADO')),
	CONSTRAINT FK_TEMAS_CATEGORIA FOREIGN KEY (CATEGORIA_ID) REFERENCES CATEGORIAS (ID),
	CONSTRAINT FK_TEMAS_AUTOR FOREIGN KEY (AUTOR_ID) REFERENCES USUARIOS (ID)
);

CREATE TABLE COMENTARIOS (
	ID NUMBER(19) PRIMARY KEY,
	CONTENIDO VARCHAR2(2000 CHAR) NOT NULL,
	FECHA_CREACION TIMESTAMP NOT NULL,
	ESTADO VARCHAR2(20 CHAR) NOT NULL,
	TEMA_ID NUMBER(19) NOT NULL,
	AUTOR_ID NUMBER(19) NOT NULL,
	CONSTRAINT CK_COMENTARIOS_ESTADO CHECK (ESTADO IN ('PUBLICADO', 'BANEADO')),
	CONSTRAINT FK_COMENTARIOS_TEMA FOREIGN KEY (TEMA_ID) REFERENCES TEMAS (ID),
	CONSTRAINT FK_COMENTARIOS_AUTOR FOREIGN KEY (AUTOR_ID) REFERENCES USUARIOS (ID)
);
